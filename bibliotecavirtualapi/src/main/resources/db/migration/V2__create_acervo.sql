-- =====================================================================
-- V2 - Acervo: autores, editoras, categorias, livros (obra) e exemplares
-- =====================================================================
-- "livro" é a obra (título/ISBN); "exemplar" é a cópia física que é
-- emprestada. Uma obra pode ter N exemplares.

CREATE TABLE autor (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    nacionalidade   VARCHAR(80),
    data_nascimento DATE,
    biografia       TEXT,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_autor_nome ON autor (lower(nome));


CREATE TABLE editora (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150) NOT NULL,
    cnpj          CHAR(14),
    site          VARCHAR(255),
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ux_editora_cnpj UNIQUE (cnpj),
    CONSTRAINT ck_editora_cnpj CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$')
);

CREATE UNIQUE INDEX ux_editora_nome ON editora (lower(nome));


CREATE TABLE categoria (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(80)  NOT NULL,
    descricao VARCHAR(255)
);

CREATE UNIQUE INDEX ux_categoria_nome ON categoria (lower(nome));


CREATE TABLE livro (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn           VARCHAR(13)  NOT NULL,
    titulo         VARCHAR(255) NOT NULL,
    subtitulo      VARCHAR(255),
    sinopse        TEXT,
    editora_id     BIGINT,
    ano_publicacao SMALLINT,
    edicao         SMALLINT,
    numero_paginas INTEGER,
    idioma         VARCHAR(5)   NOT NULL DEFAULT 'pt-BR',
    capa_url       VARCHAR(500),
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_livro_editora FOREIGN KEY (editora_id) REFERENCES editora (id),
    CONSTRAINT ux_livro_isbn    UNIQUE (isbn),
    CONSTRAINT ck_livro_isbn    CHECK (isbn ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),  -- ISBN-10 ou ISBN-13
    CONSTRAINT ck_livro_ano     CHECK (ano_publicacao IS NULL OR ano_publicacao BETWEEN 1400 AND 2100),
    CONSTRAINT ck_livro_edicao  CHECK (edicao IS NULL OR edicao > 0),
    CONSTRAINT ck_livro_paginas CHECK (numero_paginas IS NULL OR numero_paginas > 0)
);

CREATE INDEX ix_livro_titulo  ON livro (lower(titulo));
CREATE INDEX ix_livro_editora ON livro (editora_id);


-- N:N livro <-> autor (com ordem de autoria para exibição)
CREATE TABLE livro_autor (
    livro_id BIGINT   NOT NULL,
    autor_id BIGINT   NOT NULL,
    ordem    SMALLINT NOT NULL DEFAULT 1,

    CONSTRAINT pk_livro_autor       PRIMARY KEY (livro_id, autor_id),
    CONSTRAINT fk_livro_autor_livro FOREIGN KEY (livro_id) REFERENCES livro (id) ON DELETE CASCADE,
    CONSTRAINT fk_livro_autor_autor FOREIGN KEY (autor_id) REFERENCES autor (id)
);

CREATE INDEX ix_livro_autor_autor ON livro_autor (autor_id);


-- N:N livro <-> categoria
CREATE TABLE livro_categoria (
    livro_id     BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,

    CONSTRAINT pk_livro_categoria           PRIMARY KEY (livro_id, categoria_id),
    CONSTRAINT fk_livro_categoria_livro     FOREIGN KEY (livro_id)     REFERENCES livro (id) ON DELETE CASCADE,
    CONSTRAINT fk_livro_categoria_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
);

CREATE INDEX ix_livro_categoria_categoria ON livro_categoria (categoria_id);


-- Exemplar físico. "version" = optimistic locking (evita dois empréstimos
-- simultâneos do mesmo exemplar em requisições concorrentes).
CREATE TABLE exemplar (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id            BIGINT      NOT NULL,
    codigo_tombo        VARCHAR(30) NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',
    estado_conservacao  VARCHAR(20) NOT NULL DEFAULT 'BOM',
    localizacao         VARCHAR(50),           -- ex.: "Estante 3 / Prateleira B"
    data_aquisicao      DATE,
    observacao          VARCHAR(255),
    version             BIGINT      NOT NULL DEFAULT 0,
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_exemplar_livro    FOREIGN KEY (livro_id) REFERENCES livro (id),
    CONSTRAINT ux_exemplar_tombo    UNIQUE (codigo_tombo),
    CONSTRAINT ck_exemplar_status   CHECK (status IN ('DISPONIVEL', 'EMPRESTADO', 'RESERVADO', 'EM_MANUTENCAO', 'EXTRAVIADO', 'BAIXADO')),
    CONSTRAINT ck_exemplar_conserv  CHECK (estado_conservacao IN ('NOVO', 'BOM', 'REGULAR', 'RUIM'))
);

CREATE INDEX ix_exemplar_livro_status ON exemplar (livro_id, status);
