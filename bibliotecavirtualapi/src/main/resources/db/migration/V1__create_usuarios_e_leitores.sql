-- =====================================================================
-- V1 - Usuários (autenticação) e Leitores (perfil de quem pega livros)
-- =====================================================================

-- Usuário do sistema: credenciais + papel. Bibliotecários/admins são só
-- usuários; leitores têm um registro complementar na tabela "leitor".
CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    senha_hash      VARCHAR(255) NOT NULL,
    perfil          VARCHAR(20)  NOT NULL DEFAULT 'LEITOR',
    ativo           BOOLEAN      NOT NULL DEFAULT TRUE,
    ultimo_login_em TIMESTAMPTZ,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'BIBLIOTECARIO', 'LEITOR'))
);

-- e-mail único sem diferenciar maiúsculas/minúsculas
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(email));


-- Leitor: dados pessoais, situação cadastral e controle de bloqueios.
CREATE TABLE leitor (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id         BIGINT       NOT NULL,
    numero_carteirinha VARCHAR(20)  NOT NULL,
    cpf                CHAR(11)     NOT NULL,
    data_nascimento    DATE         NOT NULL,
    telefone           VARCHAR(20),
    tipo               VARCHAR(20)  NOT NULL DEFAULT 'COMUM',
    status             VARCHAR(20)  NOT NULL DEFAULT 'ATIVO',
    suspenso_ate       DATE,
    motivo_bloqueio    VARCHAR(255),

    -- endereço
    cep                CHAR(8),
    logradouro         VARCHAR(150),
    numero             VARCHAR(10),
    complemento        VARCHAR(100),
    bairro             VARCHAR(100),
    cidade             VARCHAR(100),
    uf                 CHAR(2),

    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_leitor_usuario     FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ux_leitor_usuario     UNIQUE (usuario_id),
    CONSTRAINT ux_leitor_carteirinha UNIQUE (numero_carteirinha),
    CONSTRAINT ux_leitor_cpf         UNIQUE (cpf),
    CONSTRAINT ck_leitor_cpf         CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_leitor_cep         CHECK (cep IS NULL OR cep ~ '^[0-9]{8}$'),
    CONSTRAINT ck_leitor_tipo        CHECK (tipo IN ('COMUM', 'ESTUDANTE', 'PROFESSOR')),
    CONSTRAINT ck_leitor_status      CHECK (status IN ('ATIVO', 'SUSPENSO', 'BLOQUEADO', 'INATIVO')),
    -- suspensão sempre tem data de fim
    CONSTRAINT ck_leitor_suspensao   CHECK (status <> 'SUSPENSO' OR suspenso_ate IS NOT NULL)
);

CREATE INDEX ix_leitor_status ON leitor (status);
