-- =====================================================================
-- V3 - Circulação: empréstimos (locações), renovações, reservas e multas
-- =====================================================================

-- Empréstimo de UM exemplar para UM leitor.
-- Fluxo de status: ATIVO -> DEVOLVIDO | EXTRAVIADO
-- (o "atraso" é derivado de data_prevista_devolucao < hoje, não é status
--  persistido, para não depender de job para mudar estado)
CREATE TABLE emprestimo (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leitor_id                BIGINT      NOT NULL,
    exemplar_id              BIGINT      NOT NULL,
    reserva_id               BIGINT,                 -- preenchido se originado de reserva (FK adicionada abaixo)
    registrado_por_id        BIGINT      NOT NULL,   -- bibliotecário que realizou o empréstimo
    recebido_por_id          BIGINT,                 -- bibliotecário que recebeu a devolução
    data_emprestimo          TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_prevista_devolucao  DATE        NOT NULL,
    data_devolucao           TIMESTAMPTZ,
    quantidade_renovacoes    SMALLINT    NOT NULL DEFAULT 0,
    status                   VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    observacao               VARCHAR(255),
    version                  BIGINT      NOT NULL DEFAULT 0,
    criado_em                TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em            TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_emprestimo_leitor         FOREIGN KEY (leitor_id)         REFERENCES leitor (id),
    CONSTRAINT fk_emprestimo_exemplar       FOREIGN KEY (exemplar_id)       REFERENCES exemplar (id),
    CONSTRAINT fk_emprestimo_registrado_por FOREIGN KEY (registrado_por_id) REFERENCES usuario (id),
    CONSTRAINT fk_emprestimo_recebido_por   FOREIGN KEY (recebido_por_id)   REFERENCES usuario (id),
    CONSTRAINT ck_emprestimo_status         CHECK (status IN ('ATIVO', 'DEVOLVIDO', 'EXTRAVIADO')),
    CONSTRAINT ck_emprestimo_renovacoes     CHECK (quantidade_renovacoes >= 0),
    -- devolvido <=> tem data de devolução
    CONSTRAINT ck_emprestimo_devolucao      CHECK ((status = 'DEVOLVIDO') = (data_devolucao IS NOT NULL))
);

-- Garantia no banco: um exemplar só pode ter UM empréstimo ativo.
CREATE UNIQUE INDEX ux_emprestimo_exemplar_ativo ON emprestimo (exemplar_id) WHERE status = 'ATIVO';
CREATE INDEX ix_emprestimo_leitor_status ON emprestimo (leitor_id, status);
-- consulta de atrasados (job de notificação / multa)
CREATE INDEX ix_emprestimo_atrasados ON emprestimo (data_prevista_devolucao) WHERE status = 'ATIVO';


-- Histórico de renovações (auditoria do prazo original vs. novo prazo)
CREATE TABLE renovacao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id        BIGINT      NOT NULL,
    data_renovacao       TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_prevista_antiga DATE        NOT NULL,
    data_prevista_nova   DATE        NOT NULL,
    renovado_por_id      BIGINT      NOT NULL,   -- leitor (autoatendimento) ou bibliotecário

    CONSTRAINT fk_renovacao_emprestimo   FOREIGN KEY (emprestimo_id)   REFERENCES emprestimo (id),
    CONSTRAINT fk_renovacao_renovado_por FOREIGN KEY (renovado_por_id) REFERENCES usuario (id),
    CONSTRAINT ck_renovacao_datas        CHECK (data_prevista_nova > data_prevista_antiga)
);

CREATE INDEX ix_renovacao_emprestimo ON renovacao (emprestimo_id);


-- Reserva é feita sobre a OBRA (livro), não sobre um exemplar específico.
-- Fluxo: AGUARDANDO (na fila) -> DISPONIVEL (exemplar separado, prazo p/ retirar)
--        -> ATENDIDA (virou empréstimo) | EXPIRADA | CANCELADA
CREATE TABLE reserva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leitor_id       BIGINT      NOT NULL,
    livro_id        BIGINT      NOT NULL,
    exemplar_id     BIGINT,                 -- definido quando um exemplar é separado
    status          VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO',
    data_reserva    TIMESTAMPTZ NOT NULL DEFAULT now(),
    disponivel_em   TIMESTAMPTZ,
    expira_em       TIMESTAMPTZ,            -- limite para retirada após ficar DISPONIVEL
    finalizada_em   TIMESTAMPTZ,
    version         BIGINT      NOT NULL DEFAULT 0,
    criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_reserva_leitor     FOREIGN KEY (leitor_id)   REFERENCES leitor (id),
    CONSTRAINT fk_reserva_livro      FOREIGN KEY (livro_id)    REFERENCES livro (id),
    CONSTRAINT fk_reserva_exemplar   FOREIGN KEY (exemplar_id) REFERENCES exemplar (id),
    CONSTRAINT ck_reserva_status     CHECK (status IN ('AGUARDANDO', 'DISPONIVEL', 'ATENDIDA', 'EXPIRADA', 'CANCELADA')),
    CONSTRAINT ck_reserva_disponivel CHECK (status <> 'DISPONIVEL' OR (exemplar_id IS NOT NULL AND expira_em IS NOT NULL))
);

-- leitor não pode ter duas reservas em aberto para a mesma obra
CREATE UNIQUE INDEX ux_reserva_leitor_livro_aberta ON reserva (leitor_id, livro_id)
    WHERE status IN ('AGUARDANDO', 'DISPONIVEL');
-- fila de espera por obra (ordem de chegada)
CREATE INDEX ix_reserva_fila ON reserva (livro_id, data_reserva) WHERE status = 'AGUARDANDO';
-- job de expiração
CREATE INDEX ix_reserva_expiracao ON reserva (expira_em) WHERE status = 'DISPONIVEL';

ALTER TABLE emprestimo
    ADD CONSTRAINT fk_emprestimo_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id);


-- Multa por atraso ou extravio. Gerada na devolução (ou na baixa por extravio).
CREATE TABLE multa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id  BIGINT        NOT NULL,
    leitor_id      BIGINT        NOT NULL,   -- desnormalizado p/ consultar débitos do leitor sem join
    motivo         VARCHAR(20)   NOT NULL,
    dias_atraso    INTEGER       NOT NULL DEFAULT 0,
    valor          NUMERIC(10,2) NOT NULL,
    status         VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE',
    data_pagamento TIMESTAMPTZ,
    recebido_por_id BIGINT,
    observacao     VARCHAR(255),
    criado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_multa_emprestimo   FOREIGN KEY (emprestimo_id)   REFERENCES emprestimo (id),
    CONSTRAINT fk_multa_leitor       FOREIGN KEY (leitor_id)       REFERENCES leitor (id),
    CONSTRAINT fk_multa_recebido_por FOREIGN KEY (recebido_por_id) REFERENCES usuario (id),
    CONSTRAINT ck_multa_motivo       CHECK (motivo IN ('ATRASO', 'EXTRAVIO', 'DANO')),
    CONSTRAINT ck_multa_status       CHECK (status IN ('PENDENTE', 'PAGA', 'CANCELADA')),
    CONSTRAINT ck_multa_valor        CHECK (valor >= 0),
    CONSTRAINT ck_multa_dias         CHECK (dias_atraso >= 0),
    CONSTRAINT ck_multa_pagamento    CHECK ((status = 'PAGA') = (data_pagamento IS NOT NULL))
);

-- uma multa por motivo por empréstimo
CREATE UNIQUE INDEX ux_multa_emprestimo_motivo ON multa (emprestimo_id, motivo) WHERE status <> 'CANCELADA';
CREATE INDEX ix_multa_leitor_pendente ON multa (leitor_id) WHERE status = 'PENDENTE';
