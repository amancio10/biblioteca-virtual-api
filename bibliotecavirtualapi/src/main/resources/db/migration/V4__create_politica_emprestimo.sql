-- Tira as regras de negócio do código: prazo, limite, renovações e multa
-- podem ser ajustados pelo ADMIN sem novo deploy.

CREATE TABLE politica_emprestimo (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_leitor                VARCHAR(20)   NOT NULL,
    prazo_dias                 SMALLINT      NOT NULL,
    max_emprestimos_simultaneos SMALLINT     NOT NULL,
    max_renovacoes             SMALLINT      NOT NULL,
    max_reservas_simultaneas   SMALLINT      NOT NULL,
    horas_retirada_reserva     SMALLINT      NOT NULL,   -- prazo p/ retirar reserva disponível
    valor_multa_diaria         NUMERIC(10,2) NOT NULL,
    dias_suspensao_por_atraso  SMALLINT      NOT NULL DEFAULT 0, -- dias de suspensão por dia de atraso (0 = só multa)
    atualizado_em              TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ux_politica_tipo_leitor UNIQUE (tipo_leitor),
    CONSTRAINT ck_politica_tipo_leitor CHECK (tipo_leitor IN ('COMUM', 'ESTUDANTE', 'PROFESSOR')),
    CONSTRAINT ck_politica_valores     CHECK (
        prazo_dias > 0
        AND max_emprestimos_simultaneos > 0
        AND max_renovacoes >= 0
        AND max_reservas_simultaneas >= 0
        AND horas_retirada_reserva > 0
        AND valor_multa_diaria >= 0
        AND dias_suspensao_por_atraso >= 0
    )
);

